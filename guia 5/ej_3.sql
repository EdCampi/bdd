-- 3. Obtener los clientes con edad menor a 65 años.

SELECT *
FROM CLIENTES
WHERE EXTRACT(YEAR FROM AGE(Fecha_nacimiento)) > 65;

-- 4. Obtener los préstamos a clientes, con un monto mayor a $50.000.000.

SELECT Monto, Dni_cliente, Nombre, Apellido
FROM PRESTAMOS
         JOIN CLIENTES C ON PRESTAMOS.DNI_cliente = C.DNI
WHERE Monto > 50000000;

-- 5. Obtener los préstamos a empresas, con un interés mayor al 60%.

SELECT Monto, Interes, Razon_social
FROM PRESTAMOS
         JOIN EMPRESAS ON PRESTAMOS.CUIT_empresa = EMPRESAS.CUIT
WHERE Interes > 0.6;

-- 6. Obtener las empresas (cuit y razón social) que tienen la máxima cantidad de empleados.

SELECT Razon_social
FROM EMPRESAS
WHERE Cantidad_empleados = (SELECT MAX(Cantidad_empleados)
                            FROM EMPRESAS);

