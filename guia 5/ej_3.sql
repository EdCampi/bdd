-- Definir clave primaria, claves foráneas, y restricciones.

CREATE SCHEMA banco;

SET search_path TO banco;

CREATE TABLE CLIENTES
(
    DNI              BIGINT,
    Nombre           VARCHAR(15),
    Apellido         VARCHAR(15),
    Fecha_nacimiento DATE,
    PRIMARY KEY (DNI)
);

CREATE TABLE EMPRESAS
(
    CUIT               BIGINT,
    Razon_social       VARCHAR(20) NOT NULL,
    Cantidad_empleados BIGINT,
    Patrimonio         FLOAT,
    PRIMARY KEY (CUIT)
);

CREATE TABLE PRESTAMOS
(
    ID           BIGINT,
    Monto        BIGINT,
    Interes      FLOAT,
    DNI_cliente  INT,
    CUIT_empresa BIGINT,
    PRIMARY KEY (ID),
    FOREIGN KEY (DNI_cliente) REFERENCES CLIENTES (DNI),
    FOREIGN KEY (CUIT_empresa) REFERENCES EMPRESAS (CUIT)
);

